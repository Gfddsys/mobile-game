using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace TurtleBlaster.EditorTools
{
    /// <summary>
    /// Art pipeline helpers.
    ///  - Export the code-generated placeholder sprites as PNG templates (+ a size list).
    ///  - Any PNG dropped into Resources/Sprites (or the Placeholders folder) is imported automatically
    ///    with the right settings: Point filter, no compression, and the SAME pivot and world size as the
    ///    placeholder it replaces. Artists may draw at any resolution (2x, 4x...) as long as the aspect
    ///    ratio matches; pixels-per-unit is scaled to keep the in-game size.
    ///  - Validate: lists overrides and warns about unknown names or wrong proportions.
    /// See docs/ART_GUIDE.md.
    /// </summary>
    public static class ArtTools
    {
        public const string OverrideDir = "Assets/_Project/Resources/Sprites";
        public const string PlaceholderDir = "Assets/_Project/Art/Placeholders";

        [MenuItem("Turtle Blaster/Art/1. Export Placeholder Sprites (templates)")]
        public static void ExportPlaceholderSprites()
        {
            Directory.CreateDirectory(PlaceholderDir);
            var list = new StringBuilder();
            list.AppendLine("# Sprite list (generated by Turtle Blaster > Art > Export Placeholder Sprites)");
            list.AppendLine();
            list.AppendLine("| File | Size (px) | Pixels Per Unit | In-game size (units) | Pivot (0-1) |");
            list.AppendLine("|---|---|---|---|---|");

            foreach (var name in SpriteLibrary.OverridableNames)
            {
                var sprite = SpriteLibrary.CreatePlaceholder(name);
                if (sprite == null) continue;
                var r = sprite.rect;
                var pivot = sprite.pivot / r.size;
                File.WriteAllBytes(Path.Combine(PlaceholderDir, name + ".png"), sprite.texture.EncodeToPNG());
                list.AppendLine("| " + name + ".png | " + (int)r.width + " x " + (int)r.height + " | " + sprite.pixelsPerUnit +
                                " | " + (r.width / sprite.pixelsPerUnit).ToString("0.##") + " x " + (r.height / sprite.pixelsPerUnit).ToString("0.##") +
                                " | " + pivot.x.ToString("0.##") + ", " + pivot.y.ToString("0.##") + " |");
                Object.DestroyImmediate(sprite.texture);
                Object.DestroyImmediate(sprite);
            }
            File.WriteAllText(Path.Combine(PlaceholderDir, "SPRITES.md"), list.ToString());
            Directory.CreateDirectory(OverrideDir);
            AssetDatabase.Refresh();
            Debug.Log("[TurtleBlaster] Exported placeholder sprites to " + PlaceholderDir +
                      ". Copy one into " + OverrideDir + " (same file name), paint over it, and it replaces the placeholder in game.");
        }

        [MenuItem("Turtle Blaster/Art/2. Validate Art Overrides")]
        public static void ValidateOverrides()
        {
            if (!Directory.Exists(OverrideDir)) { Debug.Log("[TurtleBlaster] No art overrides yet (" + OverrideDir + " does not exist)."); return; }
            var known = new HashSet<string>(SpriteLibrary.OverridableNames);
            int ok = 0, problems = 0;
            foreach (var file in Directory.GetFiles(OverrideDir, "*.png"))
            {
                string name = Path.GetFileNameWithoutExtension(file);
                if (!known.Contains(name))
                {
                    Debug.LogWarning("[Art] " + name + ".png is not used by the game (unknown name). Valid names: " + string.Join(", ", known));
                    problems++;
                    continue;
                }
                string msg = CheckProportions(file.Replace('\\', '/'), name);
                if (msg != null) { Debug.LogWarning("[Art] " + msg); problems++; }
                else ok++;
            }
            Debug.Log("[TurtleBlaster] Art overrides: " + ok + " OK, " + problems + " with warnings.");
        }

        [MenuItem("Turtle Blaster/Art/3. Show Art Override Folder")]
        public static void ShowOverrideFolder()
        {
            Directory.CreateDirectory(OverrideDir);
            AssetDatabase.Refresh();
            var folder = AssetDatabase.LoadAssetAtPath<Object>(OverrideDir);
            if (folder != null) { Selection.activeObject = folder; EditorGUIUtility.PingObject(folder); }
            EditorUtility.RevealInFinder(OverrideDir);
        }

        /// <summary>Returns a warning text when the art does not match the placeholder's proportions, else null.</summary>
        public static string CheckProportions(string assetPath, string name)
        {
            var importer = AssetImporter.GetAtPath(assetPath) as TextureImporter;
            var reference = SpriteLibrary.CreatePlaceholder(name);
            if (importer == null || reference == null) return null;
            try
            {
                importer.GetSourceTextureWidthAndHeight(out int w, out int h);
                float sx = w / reference.rect.width, sy = h / reference.rect.height;
                if (Mathf.Abs(sx - sy) > 0.02f * sx)
                    return name + ".png is " + w + "x" + h + " but should keep the template's proportions (" +
                           (int)reference.rect.width + "x" + (int)reference.rect.height + ", or a multiple like " +
                           (int)(reference.rect.width * 2) + "x" + (int)(reference.rect.height * 2) + "). It will look stretched or misaligned.";
                return null;
            }
            finally
            {
                Object.DestroyImmediate(reference.texture);
                Object.DestroyImmediate(reference);
            }
        }
    }

    /// <summary>Automatic import settings for game sprites (see ArtTools).</summary>
    public class ArtImportPostprocessor : AssetPostprocessor
    {
        void OnPreprocessTexture()
        {
            string path = assetPath.Replace('\\', '/');
            if (!path.StartsWith(ArtTools.OverrideDir + "/") && !path.StartsWith(ArtTools.PlaceholderDir + "/")) return;

            var importer = (TextureImporter)assetImporter;
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Single;
            importer.filterMode = FilterMode.Point;
            importer.textureCompression = TextureImporterCompression.Uncompressed;
            importer.mipmapEnabled = false;
            importer.alphaIsTransparency = true;
            importer.wrapMode = TextureWrapMode.Clamp;

            string name = Path.GetFileNameWithoutExtension(path);
            var reference = SpriteLibrary.CreatePlaceholder(name);
            if (reference == null)
            {
                if (path.StartsWith(ArtTools.OverrideDir + "/"))
                    Debug.LogWarning("[Art] " + name + ".png in Resources/Sprites does not match any game sprite name, so it will not be used. " +
                                     "Run Turtle Blaster > Art > Export Placeholder Sprites to see the valid names.");
                return;
            }

            try
            {
                importer.GetSourceTextureWidthAndHeight(out int w, out int h);
                float scale = w / reference.rect.width;   // 2 = drawn at double resolution

                var settings = new TextureImporterSettings();
                importer.ReadTextureSettings(settings);
                settings.spriteAlignment = (int)SpriteAlignment.Custom;
                settings.spritePivot = reference.pivot / reference.rect.size;   // same anchor point as the placeholder
                settings.spritePixelsPerUnit = reference.pixelsPerUnit * scale;  // same size in the world
                settings.spriteBorder = reference.border * scale;                // 9-slice borders (UI panels)
                settings.spriteMeshType = SpriteMeshType.FullRect;
                importer.SetTextureSettings(settings);

                float sy = h / reference.rect.height;
                if (Mathf.Abs(scale - sy) > 0.02f * scale)
                    Debug.LogWarning("[Art] " + name + ".png (" + w + "x" + h + ") does not keep the template's proportions (" +
                                     (int)reference.rect.width + "x" + (int)reference.rect.height + "). Width decides the scale; it may look misaligned.");
            }
            finally
            {
                Object.DestroyImmediate(reference.texture);
                Object.DestroyImmediate(reference);
            }
        }
    }
}
